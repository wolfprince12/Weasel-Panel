# ── s2t 之后再补的极少数词 ────────────────────────────────────────────
# s2t 转对字但转错义的地方。key 是 s2t 的输出形态。
POST_OVERRIDES = {
    # 输入法名取自毛笔名「鼠鬚管」（鬚＝胡须），不是「必須」的須
    "鼠須管": "鼠鬚管",
    # 下面三个是 OpenCC 的「正字偏好」：它选的是《康熙字典》正体，
    # 但现代繁体界面（含 Windows 繁中版）通用的是另一种写法。
    # 留着古字会让界面显得像古籍，统一改回来。
    "爲": "為",      # 顯示爲 / 作爲 → 顯示為 / 作為
    "啓": "啟",      # 重啓 → 重啟
    "纔": "才",      # 纔會生效 → 才會生效
}

# 幂等自检的白名单：这些字在正体里本来就正确，但 s2t 会往另一个读音转
# （后面→後面、里面→裏面、制造→製造、干部→幹部…），本包里出现属正常。
# 「才」也在此列：它本身是正字，是 s2t 偏要把「才會」转成古字「纔會」，
# 而 POST_OVERRIDES 又把它改了回来 —— 不改白名单会自相矛盾地报警。
BENIGN = set("面里制干几台发脏才")

HEADER = """# Weasel Panel — UI language pack (Traditional Chinese)
#
# 由 lang.zh-Hans.txt 简繁转换而来（tools/make_zh_hant.py）：
#   术语表（界面惯例）→ OpenCC s2t（字符级）→ 个别词覆写。
# 键与简体包一一对应。之后两边各自手工维护：新增键时先改
# lang.en.txt 与 lang.zh-Hans.txt，再同步到这里。
#
# 格式见 lang.en.txt 顶部注释。
"""


def load_converter():
    try:
        import opencc
    except ImportError:
        sys.exit(
            "缺少 opencc。本脚本的字符级简繁转换依赖它（手写逐字表已被证明补不全）：\n"
            "    pip install opencc-python-reimplemented\n"
            "如果只想改个别词，直接手改 lang.zh-Hant.txt 即可，不必跑这个脚本。"
        )
    return opencc.OpenCC("s2t")


def main() -> None:
    converter = load_converter()

    with io.open(SRC, encoding="utf-8") as f:
        raw = f.read()

    # 丢掉简体包自己的头部注释，换成繁体包的说明
    body = raw.split("\n", 1)[1] if raw.startswith("#") else raw
    while body.startswith("#"):
        body = body.split("\n", 1)[1]

    text = body
    # 1) 术语表：长词先替
    for s, t in sorted(PHRASES.items(), key=lambda kv: -len(kv[0])):
        text = text.replace(s, t)
    # 2) OpenCC 字符级兜底
    text = converter.convert(text)
    # 3) 个别词覆写
    for s, t in POST_OVERRIDES.items():
        text = text.replace(s, t)

    with io.open(DST, "w", encoding="utf-8") as f:
        f.write(HEADER + text.lstrip("\n"))

    print("written:", DST)

    # ── 幂等自检：再跑一次 s2t，结果还变 → 仍有简体字残留 ──────────────
    # 这比硬编码「常见简体字表」可靠得多 —— 表永远补不全，而 OpenCC 知道
    # 每个简字的正体写法。人工手改繁体包后跑一次，能立刻发现漏改。
    leftovers = []
    for ln, line in enumerate(text.split("\n"), 1):
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        again = converter.convert(line)
        if again == line:
            continue
        # 只报白名单之外的字：面/里/制 等在正体里本就正确，s2t 会另择一读
        chars = {a for a, b in zip(line, again) if a != b} | \
                {b for a, b in zip(line, again) if a != b}
        chars -= BENIGN
        if chars:
            leftovers.append((ln, "".join(sorted(chars)), line.strip()[:70]))

    if leftovers:
        print("\n⚠️  仍有简体字残留（人工改一下这几行，或补进 PHRASES）：")
        for ln, chars, preview in leftovers:
            print(f"    L{ln}  残留 {chars}  {preview}")
        raise SystemExit(1)

    print("✅ 幂等自检通过：未发现简体字残留")


if __name__ == "__main__":
    os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    main()
